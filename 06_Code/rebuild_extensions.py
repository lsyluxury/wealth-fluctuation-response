#!/usr/bin/env python3
"""Recompute response-kernel and interaction summaries from archived raw paths."""
from __future__ import annotations
import os
for k in ['OPENBLAS_NUM_THREADS','OMP_NUM_THREADS','MKL_NUM_THREADS','NUMBA_NUM_THREADS']:os.environ[k]='1'
import argparse,json,shutil,subprocess,sys
from pathlib import Path
import numpy as np,pandas as pd
ROOT=Path(__file__).resolve().parents[1]
def main():
 p=argparse.ArgumentParser();p.add_argument('--out',type=Path,default=ROOT/'10_Reproduced/extensions');a=p.parse_args();out=a.out.resolve();out.mkdir(parents=True,exist_ok=True);work=out/'project'
 if work.exists():raise FileExistsError('Use an empty output workspace.')
 shutil.copytree(ROOT/'07_Simulations/response_extensions',work,ignore=shutil.ignore_patterns('__pycache__','*.pyc','*.nbc','*.nbi','*.so'))
 logs=out/'logs';logs.mkdir(exist_ok=True)
 steps=[('kernel_analyze.py',['--tag','main']),('kernel_lag_shares.py',[]),('interaction_analyze.py',['--bootstrap','1000'])]
 for script,args in steps:
  with (logs/(Path(script).stem+'.log')).open('w') as f:subprocess.run([sys.executable,str(work/'code'/script),*args],cwd=work,stdout=f,stderr=subprocess.STDOUT,check=True)
 records=[];dest=out/'Response_Extensions';dest.mkdir(exist_ok=True)
 # Tables not generated by these three analyses (initial wealth / independent
 # validation cross-table) remain clearly marked as archived input copies.
 generated={
 'kernel_advantage_covariance','kernel_raw_lags','kernel_binned','kernel_coefficients','kernel_cumulative','kernel_tails','kernel_null_diagnostics','kernel_observables','kernel_lag_shares','kernel_cumulative_difference',
 'interaction_prediction','interaction_summary','interaction_finite_lambda','interaction_neutral_baseline','interaction_symmetry','interaction_baseline_check'}
 for path in sorted((ROOT/'04_Plot_Data/Response_Extensions').glob('*.csv')):
  src=work/'data'/path.name
  if not src.exists():src=path
  a1=pd.read_csv(src);b1=pd.read_csv(path)
  if set(a1.columns)!=set(b1.columns) or len(a1)!=len(b1):raise AssertionError('shape '+path.name)
  a1=a1[b1.columns];maxerr=0.
  for c in b1:
   if pd.api.types.is_numeric_dtype(b1[c]) and pd.api.types.is_numeric_dtype(a1[c]):
    x=a1[c].to_numpy(float);y=b1[c].to_numpy(float)
    if not np.allclose(x,y,atol=5e-11,rtol=2e-11,equal_nan=True):raise AssertionError(path.name+' '+c)
    good=np.isfinite(x)&np.isfinite(y)
    if good.any():maxerr=max(maxerr,float(np.max(abs(x[good]-y[good]))))
   elif not a1[c].fillna('').astype(str).equals(b1[c].fillna('').astype(str)):raise AssertionError('text '+path.name+' '+c)
  shutil.copy2(src,dest/src.name);records.append({'table':path.name,'rows':len(a1),'max_abs_error':maxerr,'recomputed':path.stem in generated})
 report={'status':'PASS','tables':records,'scope':'Raw archived trajectories to covariance, tail, paired DID and bootstrap summaries. No new trajectories. recomputed=false means an archived input/reference table.'}
 (out/'extensions_rebuild_report.json').write_text(json.dumps(report,indent=2));print(json.dumps(report,indent=2))
if __name__=='__main__':main()
