"""Stationary P2/P3 score statistics and numerical S_d direct/FFT consistency."""
import json,math,numpy as np
from pathlib import Path
from legacy_engine import reseed
from engine_stage01 import advance_trace,initialize_process_score
from response_kernel import S_by_lag_direct,S_by_lag_fft

def evaluate(mode,p=.4,n=30000,rounds=8):
 reseed(81231+mode)
 w=np.ones((n,1));a=np.zeros(n);u=np.zeros(n);perm=np.arange(n)
 initialize_process_score(u,mode)
 if mode==3: u[:]=np.linspace(-1,1,n)
 init=u.copy(); seq=[u.copy()]
 for k in range(rounds):
  advance_trace(w,a,u,perm,np.array([0.]),np.array([0.]),1,.14,.3,1.,10,mode,p,False)
  seq.append(u.copy())
 arr=np.array(seq)
 cov=[]
 for d in (1,2,3,5):
  cov.append(float(np.mean(arr[:-d]*arr[d:])))
 var=float(np.mean(arr[0]**2))
 expected=[(1-p)**d/3 for d in (1,2,3,5)] if mode in (1,2) else [0.]*4 if mode==4 else [1/3]*4
 return dict(var=var,lags=[1,2,3,5],measured=cov,expected=expected,max_abs_error=float(np.max(abs(np.array(cov)-expected))))

if __name__=='__main__':
 out={f'process_{mode}':evaluate(mode) for mode in (1,2,4)}
 np.random.seed(3)
 # Complete matching sign sequences generated by an unbiased engine with N=400, 32 rounds.
 n=400;w=np.ones((n,1));a=np.zeros(n);u=np.zeros(n);perm=np.arange(n)
 reseed(34019)
 ss=advance_trace(w,a,u,perm,np.array([0.]),np.array([0.]),32,.14,.3,1.,10,1,.4,True)
 exact=S_by_lag_direct(ss)
 via_fft=S_by_lag_fft(ss)
 out['S_lag_checks']={'direct_first4':exact[:4].tolist(), 'fft_first4':via_fft[:4].tolist(),'max_abs_difference':float(np.max(abs(exact-via_fft)))}
 assert out['S_lag_checks']['max_abs_difference']<1e-8
 for k in ('process_1','process_2','process_4'):
  assert out[k]['max_abs_error']<.011, (k,out[k])
 dst=Path(__file__).resolve().parents[1]/'results/stationary_process_checks.json'
 dst.write_text(json.dumps(out,indent=2,ensure_ascii=False))
 print(json.dumps(out,indent=2,ensure_ascii=False))
